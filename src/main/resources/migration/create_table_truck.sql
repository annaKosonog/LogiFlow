CREATE TABLE IF NOT EXISTS trucks (
                        truck_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        uuid UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
                        license_plate VARCHAR(10) NOT NULL UNIQUE,

    -- Wymiary całkowite samochodu (X, Y, Z)
                        width_w INT NOT NULL,
                        height_h INT NOT NULL,
                        length_l INT NOT NULL,

    -- Ładowność i obecna waga
                        max_payload DECIMAL(10, 2) NOT NULL,
                        current_weight DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
                        version BIGINT NOT NULL DEFAULT 0,
                        CHECK (current_weight <=max_payload)
);